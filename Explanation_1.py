#           Apa itu programming?



# Programming = langkah-langkah / seni memberi perintah kepada 
#               komputer/robot supaya mereka paham dan
#               melakukannya dengan benar
# bahasa yang dipakai (bahasa pemrograman) = python, javascript, dll

#       Komponen utama programming
# input -> proses -> output
# proses = apa yang harus dilakukan
# input = dari mana data datang, apa yang diberikan
# output = hasilnya seperti apa

#       Contoh programming pada permainan 
# PROSES (yang ditulis programmer):
# 1. Tampilkan pilihan: [1]Batu [2]Gunting [3]Kertas
# 2. Minta player memilih (INPUT)
# 3. Komputer pilih random 1/2/3
# 4. Bandingkan pilihan player vs komputer:
#   - Kalau sama → Seri
#   - Batu > Guning → Player menang
#   - Gunting > Kertas → Player menang
#   - Kertas > Batu → Player menang
#   - Selain itu → Player kalah
# 5. Tampilkan hasil (OUTPUT)
# Programmer menulis langkah 1-5 dalam Bahasa Pemrograman.
# Saat game dijalankan, komputer mengikuti langkah tersebut.


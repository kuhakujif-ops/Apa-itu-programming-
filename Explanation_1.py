# Pertanyaan 4: Dalam konteks DevOps, kenapa programming penting?

#       Answer A
# 1. Memberikan proses/perintah yang jelas, detail, teratur kepada mesin
# 2. Mesin hanya memahami hal yang jelas & terstruktur,
#    tidak bisa paham ambigu
# 3. INPUT (data masuk), PROSES (olah data), OUTPUT (hasil keluar)
# 4. DevOps membuat instruksi yang bisa dipakai berkali-kali,
#    tanpa pemahaman tidak bisa memerintah mesin